def get_all_metric_definitions() -> List[Dict[str, str]]:
    """Return list of serialized metric definitions for API and agent inspection."""
    return [
        {
            "name": m.name,
            "display_name": m.display_name,
            "formula": m.formula,
            "unit": m.unit,
            "time_window": m.time_window,
            "null_handling": m.null_handling,
            "description": m.description,
        }
        for m in METRIC_REGISTRY.values()
    ]


def get_metric_definition(metric_name: str) -> Dict[str, str]:
    """Retrieve details for a single registered metric."""
    m = METRIC_REGISTRY.get(metric_name.lower())
    if not m:
        raise KeyError(f"Metric '{metric_name}' is not in the central registry.")
    return {
        "name": m.name,
        "display_name": m.display_name,
        "formula": m.formula,
        "unit": m.unit,
        "time_window": m.time_window,
        "null_handling": m.null_handling,
        "description": m.description,
    }
